/** First matching rule wins: household, frozen, specific products, then aisles.
 * Space boundaries prevent eggplant/egg and foil/oil substring collisions. */
export function categoriseIngredient(name: string): ShoppingCategory {
  const normalised = ` ${canonicalIngredientName(name)} `
  return (
    categoryKeywords.find(([, keywords]) =>
      keywords.some((keyword) => normalised.includes(` ${canonicalIngredientName(keyword)} `)),
    )?.[0] ?? 'other'
  )
}
